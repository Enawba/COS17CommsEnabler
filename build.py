"""Build the flashable module zip.

    python build.py                  # module only (the normal release zip)
    python build.py --with-calendar  # also bundle apk/Calendar.apk (all-in-one zip)

apk/Calendar.apk = ColorOS global Calendar (com.oplus.calendar), e.g. Calendar_17.6.30.apk

holidays_en.sed (used by service.sh to translate the Calendar's Hindi holiday list) is
generated from the NAMES / LINES tables in tools/calendar_holidays_en.py.
"""
import html
import importlib.util
import os
import re
import sys
import zipfile

ROOT = os.path.dirname(os.path.abspath(__file__))
INCLUDE = ["META-INF/com/google/android/update-binary",
           "META-INF/com/google/android/updater-script",
           "module.prop", "customize.sh", "post-fs-data.sh", "service.sh", "uninstall.sh",
           "LICENSE"]
CALENDAR = "apk/Calendar.apk"
EXECUTABLE = (".sh", "update-binary")
SED = "holidays_en.sed"


def _xml(s):
    # how Android's shared_prefs serializer escapes the JSON string
    return html.escape(s, quote=True).replace("&#x27;", "'")


def holidays_sed():
    """sed -E script translating the cached holiday list (see tools/calendar_holidays_en.py)."""
    spec = importlib.util.spec_from_file_location(
        "holidays", os.path.join(ROOT, "tools", "calendar_holidays_en.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)

    def pat(s):  # literal text -> ERE
        return re.sub(r"([.\[\]()*+?{}|^$#\\])", r"\\\1", _xml(s))

    def rep(s):  # literal text -> sed replacement
        return re.sub(r"([&#\\])", r"\\\1", _xml(s))

    q = "&quot;"
    out = ["# generated by build.py from tools/calendar_holidays_en.py - do not edit",
           rf"s# {pat(mod.TENTATIVE)}({q})# (tentative)\1#g"]
    for hi, en in mod.NAMES.items():
        out.append(rf"s#({q}summary{q}:{q}){pat(hi)}(( \(tentative\))?{q})#\1{rep(en)}\2#g")
    # description / organizer lines: whole lines only (between &quot; or a JSON \n),
    # longest first because some lines contain shorter ones
    edge = rf"({q}|\\n)"
    for hi in sorted(mod.LINES, key=len, reverse=True):
        out.append(rf"s#{edge}{pat(hi)}{edge}#\1{rep(mod.LINES[hi])}\2#g")
    return "\n".join(out) + "\n"


def main():
    with_calendar = "--with-calendar" in sys.argv[1:]
    props = dict(l.split("=", 1) for l in open(os.path.join(ROOT, "module.prop"),
                                                encoding="utf-8").read().splitlines() if "=" in l)
    files = list(INCLUDE)
    suffix = ""
    if with_calendar:
        if not os.path.exists(os.path.join(ROOT, *CALENDAR.split("/"))):
            sys.exit(f"{CALENDAR} is missing - see README 'Building from source'")
        files.append(CALENDAR)
        suffix = "_with_calendar"
    out = os.path.join(ROOT, f"{props['id']}_{props['version']}{suffix}.zip")
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as z:
        info = zipfile.ZipInfo(SED, date_time=(2026, 1, 1, 0, 0, 0))
        info.external_attr = 0o644 << 16
        info.compress_type = zipfile.ZIP_DEFLATED
        z.writestr(info, holidays_sed().encode("utf-8"))
        for rel in files:
            path = os.path.join(ROOT, *rel.split("/"))
            data = open(path, "rb").read()
            if not rel.endswith(".apk") and b"\r\n" in data:
                sys.exit(f"{rel} has CRLF line endings - fix before building")
            info = zipfile.ZipInfo(rel, date_time=(2026, 1, 1, 0, 0, 0))
            info.external_attr = (0o755 if rel.endswith(EXECUTABLE) else 0o644) << 16
            info.compress_type = zipfile.ZIP_STORED if rel.endswith(".apk") else zipfile.ZIP_DEFLATED
            z.writestr(info, data)
    print(f"built {out} ({os.path.getsize(out) / 1e6:.2f} MB)")


if __name__ == "__main__":
    main()
